def test_parse_txt_encrypted_bytes() -> None:
    """Zeroconf gives bytes keys and values, and data spans several records."""
    frame = parse_txt(
        {
            b"id": DEVICE_ID.encode(),
            b"type": b"plug",
            b"seq": b"42",
            b"encrypt": b"true",
            b"iv": b"abc=",
            b"data2": b"world",
            b"data1": b"hello ",
            b"txtvers": None,
        }
    )
    assert frame.deviceid == DEVICE_ID
    assert frame.localtype == "plug"
    assert frame.seq == 42
    assert frame.encrypted is True
    assert frame.iv == "abc="
    assert frame.data == "hello world"


@pytest.mark.parametrize(
    ("properties", "encrypted"),
    [
        ({"encrypt": "true", "iv": "x"}, True),
        ({"encrypt": "True", "iv": "x"}, True),
        ({"encrypt": "1", "iv": "x"}, True),
        # SonoffLAN #1886: the key may be present with a false value.
        ({"encrypt": "false"}, False),
        ({"encrypt": "false", "iv": "x"}, False),
        ({"iv": "x"}, True),
        ({}, False),
    ],
)
def test_encryption_detection(properties: dict[str, str], encrypted: bool) -> None:
    """Detection reads the flag's value, and falls back to the iv only when absent."""
    assert parse_txt(properties).encrypted is encrypted


def test_parse_txt_tolerates_bad_seq() -> None:
    """A malformed sequence number must not lose the frame."""
    assert parse_txt({"seq": "abc"}).seq is None


def test_decode_txt_encrypted_round_trip() -> None:
    """A frame split over several TXT records decrypts in order."""
    device = FakeS60TPF()
    frame = parse_txt(device.txt())
    assert frame.data.count("=") <= 2
    assert decode_txt(frame, DEVICE_KEY) == device.state


def test_decode_txt_plain() -> None:
    """Plain frames are JSON, spanning several records if needed."""
    device = FakeS60TPF(devicekey=None)
    txt = device.txt()
    assert "data2" in txt
    assert decode_txt(parse_txt(txt), None) == device.state


def test_decode_txt_without_key() -> None:
    """Encrypted frames need a key."""
    frame = parse_txt(FakeS60TPF().txt())
    with pytest.raises(SonoffEncryptionRequired):
        decode_txt(frame, None)


def test_decode_txt_without_iv() -> None:
    """An encrypted flag with no iv cannot be decoded."""
    with pytest.raises(SonoffDecryptError):
        decode_txt(parse_txt({"encrypt": "true", "data1": "AAAA"}), DEVICE_KEY)


def test_decode_txt_empty() -> None:
    """Some devices publish no data at all."""
    assert decode_txt(parse_txt({"id": DEVICE_ID}), None) == {}


@pytest.mark.parametrize("data", ["{broken", "[1,2]"])
def test_decode_txt_invalid_plain(data: str) -> None:
    """Plain frames must be JSON objects."""
    with pytest.raises(SonoffProtocolError):
        decode_txt(parse_txt({"data1": data}), None)


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        # UIID 190, from issue #1514 diagnostics.
        (23717, 237.17),
        (724, 7.24),
        (5, 0.05),
        (117, 1.17),
        (0, 0.0),
        ("23717", 237.17),
        # UIID 32, from SonoffLAN's test fixture.
        ("234.20", 234.2),
        ("12.34", 12.34),
        ("1.23", 1.23),
        (234.2, 234.2),
        # Unusable values.
        (None, None),
        (True, None),
        ("n/a", None),
        ("nan", None),
        ("inf", None),
        ({}, None),
    ],
)
def test_scale_metric(raw: Any, expected: float | None) -> None:
    """Both raw forms convert, and junk gives None."""
    assert scale_metric(raw) == expected


def test_uiid190_scale_matches_device_thresholds() -> None:
    """The scale must give sensible limits for a 230 V, 16 A, 4 kW socket.

    Issue #1514 reports thresholds of 27700 for voltage, 1700 for current and 400000
    for active power. These limits are the evidence for the factor of 0.01.
    """
    assert scale_metric(27700) == 277.0
    assert scale_metric(1700) == 17.0
    assert scale_metric(400000) == 4000.0


