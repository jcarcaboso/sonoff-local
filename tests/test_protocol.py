# Public fixture from SonoffLAN's tests/test_misc.py (test_issue_1160). It is the only
# vector here not generated by this project's own code, so it is an independent check
# of the cipher parameters. The plaintext has a trailing-byte quirk from real firmware.
UPSTREAM_KEY = "9b0810bc-557a-406c-8266-614767890531"
UPSTREAM_IV = "MTA4MDc1MTQ5NzE5ODE2Ng=="
UPSTREAM_DATA = (
    "D85ho6GLI5uFX2b1+vohUIb+Xt99f55wxsBsNhqpPQdQ/WNc3ZTlCi1UVFiFU5cnaCPjvXPG6pqf"
    "HqXdtCO2fA=="
)


def test_decrypts_upstream_vector() -> None:
    """Match an independently produced ciphertext."""
    assert decrypt_params(UPSTREAM_DATA, UPSTREAM_IV, UPSTREAM_KEY) == {
        "switches": [{"outlet": 0, "switch": "off"}]
    }


def test_encrypt_round_trip() -> None:
    """Encrypted data decrypts back to the same object."""
    params = {"switches": [{"outlet": 0, "switch": "on"}], "operSide": 1}
    data, iv = encrypt_params(params, DEVICE_KEY)
    assert len(base64.b64decode(iv)) == 16
    assert decrypt_params(data, iv, DEVICE_KEY) == params


def test_encrypt_uses_fresh_iv() -> None:
    """The same plaintext must never reuse an IV."""
    first = encrypt_params({"switch": "on"}, DEVICE_KEY)
    second = encrypt_params({"switch": "on"}, DEVICE_KEY)
    assert first[1] != second[1]
    assert first[0] != second[0]


def test_encrypted_plaintext_is_compact() -> None:
    """Spaces in the JSON make some firmware silently ignore commands."""
    assert protocol.encode_json({"a": [{"b": 1}]}) == b'{"a":[{"b":1}]}'


def test_wrong_key_is_reported() -> None:
    """A wrong key must not produce state, whatever the padding happens to do."""
    data, iv = encrypt_params({"switch": "on"}, DEVICE_KEY)
    with pytest.raises(SonoffDecryptError):
        decrypt_params(data, iv, "wrong-key")


@pytest.mark.parametrize(
    ("data", "iv"),
    [
        ("not base64!!", "AAAAAAAAAAAAAAAAAAAAAA=="),  # Bad ciphertext.
        ("AAAA", "AAAAAAAAAAAAAAAAAAAAAA=="),  # Not a whole block.
        ("AAAAAAAAAAAAAAAAAAAAAA==", "AAAA"),  # IV too short.
    ],
)
def test_malformed_ciphertext(data: str, iv: str) -> None:
    """Malformed input raises the protocol's error, not a bare ValueError."""
    with pytest.raises(SonoffDecryptError):
        decrypt_params(data, iv, DEVICE_KEY)


def test_non_object_plaintext_rejected() -> None:
    """Only JSON objects count as state."""
    key = DEVICE_KEY
    original = protocol.encode_json
    protocol.encode_json = lambda value: json.dumps(value).encode()
    try:
        data, iv = encrypt_params([1, 2], key)  # type: ignore[arg-type]
    finally:
        protocol.encode_json = original
    with pytest.raises(SonoffDecryptError):
        decrypt_params(data, iv, key)


def test_empty_encrypted_payload() -> None:
    """Some devices send an empty body with an iv."""
    assert decrypt_params("", "AAAA", DEVICE_KEY) == {}


